"""v1 event builders.

The entry point for anyone who produces data and does not want to know the
JSON:

* David (inference) → :func:`new_detection`
* Elena (sensors) → :func:`new_environment` and :func:`reading`
* Erik (monitor) → :func:`new_health`
* Any service → :func:`availability`

Each builder returns a ``dict`` **already validated** against the contract.

``event_id`` is generated here, once. Whoever retries a publication resends
the same ``dict``: they never call the builder again, because that would create
a new identifier and, with it, a duplicated observation.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any, Mapping

from .contracts import CURRENT_SCHEMA_VERSION, validate
from .timestamps import format_timestamp, now_timestamp

__all__ = [
    "new_event_id",
    "stable_event_id",
    "reading",
    "new_detection",
    "new_environment",
    "new_health",
    "availability",
]

#: Fixed namespace for deterministic identifiers. Changing it would change every
#: derived identifier: do not touch it.
_NAMESPACE = uuid.UUID("6f1d5c0a-3b7e-5e0e-9a51-7b6f0c1d2e3f")


def new_event_id() -> str:
    """Random identifier (UUID v4) for a new observation."""
    return str(uuid.uuid4())


def stable_event_id(*parts: object) -> str:
    """Deterministic identifier (UUID v5) from the identity of the observation.

    Useful when a producer can recompute the same observation after
    restarting: the same ``parts`` always give the same identifier, and
    persistence deduplicates it. Example::

        stable_event_id("detection", station_id, observed_at, scientific_name)
    """
    if not parts:
        raise ValueError("stable_event_id needs at least one component")
    return str(uuid.uuid5(_NAMESPACE, "\x1f".join(str(p) for p in parts)))


def _ts(value: str | datetime | None) -> str:
    if value is None:
        return now_timestamp()
    return format_timestamp(value) if isinstance(value, datetime) else value


def reading(value: float | None, unit: str, quality: str = "ok") -> dict[str, Any]:
    """Single reading for :func:`new_environment`.

    A failed reading is declared with ``value=None`` and ``quality`` set to
    ``"unavailable"`` or ``"error"``; the contract rejects any other
    combination, including a "filler" zero.
    """
    return {"value": value, "unit": unit, "quality": quality}


def new_detection(
    *,
    station_id: str,
    scientific_name: str,
    confidence: float,
    observed_at: str | datetime,
    window_end: str | datetime,
    model_name: str,
    model_version: str,
    taxon_key: str | None = None,
    event_id: str | None = None,
) -> dict[str, Any]:
    """Bird detection event.

    :param observed_at: start of the analysed audio window.
    :param window_end: end of the window; must be later than ``observed_at``.
    :param event_id: only to rebuild an existing event or to use
        :func:`stable_event_id`. A new one is generated by default.
    """
    species: dict[str, Any] = {"scientific_name": scientific_name}
    if taxon_key is not None:
        species["taxon_key"] = taxon_key
    event = {
        "schema_version": CURRENT_SCHEMA_VERSION,
        "event_id": event_id or new_event_id(),
        "station_id": station_id,
        "observed_at": _ts(observed_at),
        "window_end": _ts(window_end),
        "species": species,
        "confidence": confidence,
        "model": {"name": model_name, "version": model_version},
    }
    validate("detection", event)
    return event


def new_environment(
    *,
    station_id: str,
    readings: Mapping[str, Mapping[str, Any]],
    observed_at: str | datetime | None = None,
    event_id: str | None = None,
) -> dict[str, Any]:
    """Event with environmental readings taken at the same instant.

    ``readings`` maps each metric (``temperature``, ``humidity``,
    ``pressure``, ``light``) to the result of :func:`reading`.
    """
    event = {
        "schema_version": CURRENT_SCHEMA_VERSION,
        "event_id": event_id or new_event_id(),
        "station_id": station_id,
        "observed_at": _ts(observed_at),
        "readings": {metric: dict(value) for metric, value in readings.items()},
    }
    validate("environment", event)
    return event


def new_health(
    *,
    station_id: str,
    services: Mapping[str, str],
    cpu_percent: float | None = None,
    memory_used_bytes: int | None = None,
    cpu_temperature_c: float | None = None,
    disk_free_bytes: int | None = None,
    uptime_seconds: int | None = None,
    observed_at: str | datetime | None = None,
    event_id: str | None = None,
) -> dict[str, Any]:
    """Health event. A metric that could not be measured is left as ``None``."""
    event = {
        "schema_version": CURRENT_SCHEMA_VERSION,
        "event_id": event_id or new_event_id(),
        "station_id": station_id,
        "observed_at": _ts(observed_at),
        "cpu_percent": cpu_percent,
        "memory_used_bytes": memory_used_bytes,
        "cpu_temperature_c": cpu_temperature_c,
        "disk_free_bytes": disk_free_bytes,
        "uptime_seconds": uptime_seconds,
        "services": dict(services),
    }
    validate("health", event)
    return event


def availability(
    *,
    station_id: str,
    service: str,
    status: str,
    observed_at: str | datetime | None = None,
) -> dict[str, Any]:
    """``online`` or ``offline`` state of a service.

    The ``offline`` message registered as Last Will is built when connecting,
    so its ``observed_at`` is the connection time and not the failure time. It
    carries no ``event_id`` (see ``availability.schema.json``).
    """
    event = {
        "schema_version": CURRENT_SCHEMA_VERSION,
        "station_id": station_id,
        "service": service,
        "status": status,
        "observed_at": _ts(observed_at),
    }
    validate("availability", event)
    return event
