#!/usr/bin/env bash
# Collects the provisioning evidence of issue #2 in Markdown format.
#
#   ./collect_report.sh > report.md
#   ./collect_report.sh --idle-seconds 300 > report.md   # more idle time
#
# Read-only: it changes nothing on the system and does not need sudo. Each
# probe tolerates its own failure and writes "not available" instead of
# aborting, so that the report reflects what is really there and not only what
# the script expected.
#
# It does not collect network names, IP addresses, keys or user names.
set -u

IDLE_SECONDS=60
APP_HOME="${TXORI_HOME:-/opt/txori-kantua}"
DATA_DIR="${TXORI_DATA_DIR:-/var/lib/txori-kantua}"

while [ "$#" -gt 0 ]; do
  case "$1" in
    --idle-seconds) IDLE_SECONDS="${2:?missing value}"; shift 2 ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done

na="not available"
probe() { "$@" 2>/dev/null || true; }
first_line() { head -n 1; }
or_na() { local v; v="$(cat)"; [ -n "$v" ] && printf '%s' "$v" || printf '%s' "$na"; }
row() { printf '| %s | %s |\n' "$1" "$2"; }

cpu_temp() {
  if command -v vcgencmd >/dev/null 2>&1; then
    probe vcgencmd measure_temp | sed -e 's/temp=//' -e "s/'C//"
  elif [ -r /sys/class/thermal/thermal_zone0/temp ]; then
    awk '{printf "%.1f", $1/1000}' /sys/class/thermal/thermal_zone0/temp
  fi
}

os_name="$( (. /etc/os-release 2>/dev/null && printf '%s' "${PRETTY_NAME:-}") | or_na)"
model="$( { [ -r /proc/device-tree/model ] && tr -d '\0' < /proc/device-tree/model; } 2>/dev/null | or_na)"
kernel="$(probe uname -r | or_na)"
arch="$(probe uname -m | or_na)"
python_sys="$(probe python3 --version | or_na)"
python_venv="$( [ -x "$APP_HOME/venv/bin/python" ] && probe "$APP_HOME/venv/bin/python" --version | or_na || printf '%s/venv does not exist' "$APP_HOME")"
mem_total="$(probe awk '/MemTotal/ {printf "%.0f MB", $2/1024}' /proc/meminfo | or_na)"
root_disk="$(probe df -h --output=size,used,avail,pcent / | tail -n 1 | awk '{print "total "$1", used "$2", free "$3" ("$4")"}' | or_na)"
data_disk="$( [ -d "$DATA_DIR" ] && probe df -h --output=avail "$DATA_DIR" | tail -n 1 | tr -d ' ' | or_na || printf '%s does not exist' "$DATA_DIR")"
root_dev="$(probe findmnt -n -o SOURCE / | or_na)"
tz="$(probe timedatectl show -p Timezone --value | or_na)"
ntp_on="$(probe timedatectl show -p NTP --value | or_na)"
ntp_sync="$(probe timedatectl show -p NTPSynchronized --value | or_na)"
swap="$(probe swapon --show=NAME,SIZE,USED --noheadings | tr '\n' ';' )"
[ -n "$swap" ] || swap="none active"
core_pattern="$(probe cat /proc/sys/kernel/core_pattern | or_na)"
core_limit="$(ulimit -c 2>/dev/null | or_na)"
throttled="$(command -v vcgencmd >/dev/null 2>&1 && probe vcgencmd get_throttled | or_na || printf '%s' "$na")"
ssh_pw="$(probe sshd -T 2>/dev/null | awk '/^passwordauthentication/ {print $2}' | or_na)"
[ "$ssh_pw" = "$na" ] && ssh_pw="$na (run with sudo to read the effective configuration)"
uptime_s="$(probe awk '{printf "%.0f", $1}' /proc/uptime | or_na)"

# Idle temperature: three samples spread over the interval.
t0="$(cpu_temp | or_na)"
sleep "$((IDLE_SECONDS / 2))" 2>/dev/null || true
t1="$(cpu_temp | or_na)"
sleep "$((IDLE_SECONDS / 2))" 2>/dev/null || true
t2="$(cpu_temp | or_na)"
load="$(probe cut -d' ' -f1-3 /proc/loadavg | or_na)"

cat <<EOF
# Provisioning report — Raspberry Pi

- **Date (UTC):** $(date -u +%Y-%m-%dT%H:%M:%SZ)
- **Generated by:** \`deploy/provision/collect_report.sh\`
- **Repository commit:** $(probe git -C "$(dirname "$0")" rev-parse --short HEAD | or_na)
- **Run by:** _fill in_
- **Issue:** #2

## System

| Item | Value |
|---|---|
EOF
row "Model" "$model"
row "Operating system" "$os_name"
row "Kernel" "$kernel"
row "Architecture" "$arch"
row "System Python" "$python_sys"
row "Virtual environment Python" "$python_venv"
row "Total memory" "$mem_total"
row "Uptime (s)" "$uptime_s"

cat <<EOF

## Storage

| Item | Value |
|---|---|
EOF
row "Root device" "$root_dev"
row "Root" "$root_disk"
row "Free in data directory" "$data_disk"

cat <<EOF

## Clock

| Item | Value |
|---|---|
EOF
row "Time zone" "$tz"
row "NTP enabled" "$ntp_on"
row "Clock synchronised" "$ntp_sync"

cat <<EOF

## Idle temperature

Three samples over ${IDLE_SECONDS} s, with no application services running.

| Item | Value |
|---|---|
EOF
row "Initial temperature (°C)" "$t0"
row "Middle temperature (°C)" "$t1"
row "Final temperature (°C)" "$t2"
row "Load average (1, 5, 15 min)" "$load"
row "Power status (get_throttled)" "$throttled"

cat <<EOF

A \`get_throttled\` other than \`throttled=0x0\` indicates under-voltage or
thermal throttling since boot: review power supply and cooling.

## Access and privacy

| Item | Value |
|---|---|
EOF
row "SSH with password" "$ssh_pw"
row "Active swap" "$swap"
row "Dump pattern (core_pattern)" "\`$core_pattern\`"
row "Core dump limit of this session" "$core_limit"

cat <<EOF

## Dependencies installed in the virtual environment

\`\`\`text
$( [ -x "$APP_HOME/venv/bin/python" ] && probe "$APP_HOME/venv/bin/python" -m pip freeze --disable-pip-version-check | or_na || printf '%s' "$na")
\`\`\`

## To fill in by hand

- Power supply (model and wattage):
- Cooling (heatsink, fan, case):
- Storage medium (card or SSD, capacity, model):
- SSH access with key checked **after a reboot**: yes / no
- Second member who reproduced the environment from the instructions, and date:
- Incidents and limitations:
EOF
