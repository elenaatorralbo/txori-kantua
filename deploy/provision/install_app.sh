#!/usr/bin/env bash
# Installs the application into the virtual environment created by provision.sh (issue #2).
#
#   sudo ./install_app.sh              # installs; honours the pinned versions file if present
#   sudo ./install_app.sh --freeze     # also writes the installed versions
#   sudo ./install_app.sh --with-dev   # includes pytest to run the tests on the Pi
#
# Reproducibility: the first installation verified on the Pi is frozen with
# --freeze into deploy/requirements-pi.lock and that file is committed. From
# then on every installation uses exactly those versions. The file does NOT
# exist until someone generates it on a real Raspberry Pi: "verified on ARM64"
# versions are not invented from another machine.
#
# STATUS: written without access to the Raspberry Pi; not run on real hardware.
set -euo pipefail

APP_USER="${TXORI_USER:-txori}"
APP_HOME="${TXORI_HOME:-/opt/txori-kantua}"
REPO_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
LOCK="$REPO_DIR/deploy/requirements-pi.lock"
VENV="$APP_HOME/venv"
SRC="$APP_HOME/app"

FREEZE=0
EXTRAS=""
for arg in "$@"; do
  case "$arg" in
    --freeze) FREEZE=1 ;;
    --with-dev) EXTRAS="[dev]" ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

log() { printf '[install] %s\n' "$*"; }
die() { printf '[install] ERROR: %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "run with sudo"
[ -x "$VENV/bin/python" ] || die "$VENV does not exist: run provision.sh first"
as_app() { sudo -u "$APP_USER" "$@"; }

# Copy of the code owned by the service user. It is copied instead of
# installed from the home directory of whoever deploys, so that the service
# does not depend on the permissions of that folder.
log "copying the code to $SRC (commit $(git -C "$REPO_DIR" rev-parse --short HEAD 2>/dev/null || echo unknown))"
install -d -o "$APP_USER" -g "$APP_USER" -m 0755 "$SRC"
for item in pyproject.toml README.md src contracts tests; do
  rm -rf "${SRC:?}/$item"
  cp -a "$REPO_DIR/$item" "$SRC/$item"
done
git -C "$REPO_DIR" rev-parse HEAD > "$SRC/COMMIT" 2>/dev/null || echo unknown > "$SRC/COMMIT"
chown -R "$APP_USER:$APP_USER" "$SRC"

as_app "$VENV/bin/python" -m pip install --quiet --upgrade pip

if [ -f "$LOCK" ]; then
  log "installing with the versions pinned in $(basename "$LOCK")"
  as_app "$VENV/bin/python" -m pip install --constraint "$LOCK" --editable "$SRC$EXTRAS"
else
  log "WARNING: $(basename "$LOCK") does not exist; installing the latest compatible versions"
  log "         once it is verified to work, repeat with --freeze and commit the file"
  as_app "$VENV/bin/python" -m pip install --editable "$SRC$EXTRAS"
fi

if [ "$FREEZE" -eq 1 ]; then
  {
    echo "# Versions installed and verified on a Raspberry Pi."
    echo "# Generated by deploy/provision/install_app.sh --freeze"
    echo "# Date (UTC): $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# Hardware: $(tr -d '\0' < /proc/device-tree/model 2>/dev/null || echo unknown)"
    echo "# Python: $("$VENV/bin/python" --version 2>&1)  Architecture: $(uname -m)"
    as_app "$VENV/bin/python" -m pip freeze --exclude-editable --disable-pip-version-check
  } > "$LOCK"
  log "wrote $LOCK: review it and commit it"
fi

log "checking that the package can be imported"
as_app "$VENV/bin/python" -c "import txori_kantua, txori_kantua.messaging as m; m.load_schema('detection'); print('txori_kantua', txori_kantua.__version__, 'contracts loaded')"
log "done"
